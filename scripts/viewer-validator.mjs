import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standalone from "ajv/dist/standalone/index.js";
import esbuild from "esbuild";

// Compile at build time: browsers under our CSP cannot evaluate schemas.
// Bundle the generated validator's helpers so npm consumers need no plugin.
export async function buildValidator() {
  const root = fileURLToPath(new URL("../", import.meta.url));
  const ajv = new Ajv2020({ allowUnionTypes: true, code: { source: true, esm: true } });
  addFormats(ajv);
  const schema = JSON.parse(await readFile(path.join(root, "packages/format/session.schema.json"), "utf8"));
  const code = standalone(ajv, ajv.compile(schema));
  const result = await esbuild.build({ stdin: { contents: code, resolveDir: root }, bundle: true, minify: true, write: false, format: "esm" });
  await writeFile(path.join(root, "packages/viewer/validate-session.js"), "// Generated by scripts/viewer-validator.mjs from the canonical session schema.\n" + result.outputFiles[0].text);
}
